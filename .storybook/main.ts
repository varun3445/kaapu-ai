import type { StorybookConfig } from '@storybook/react-vite';
import { fileURLToPath } from 'url';
import path from 'path';
import type { Plugin } from 'vite';

const __dirname = path.dirname(fileURLToPath(import.meta.url));

/** Intercept AppContext and supabase imports at resolve-time, before Vite adds extensions */
function mockPlugin(): Plugin {
  const mockAppCtx  = path.resolve(__dirname, 'MockAppContext.jsx')
  const mockSupabase = path.resolve(__dirname, 'MockSupabase.js')

  return {
    name: 'kaapu-storybook-mocks',
    enforce: 'pre',
    resolveId(source, importer) {
      // Convert file:// absolute URLs (generated by MDX compiler) to real filesystem paths
      if (source.startsWith('file://')) return fileURLToPath(source)
      if (!importer) return null
      // Intercept any import path that ends with /context/AppContext (with or without extension)
      if (/\/context\/AppContext(\.jsx?)?$/.test(source)) return mockAppCtx
      if (/\/supabase(\.js?)?$/.test(source))             return mockSupabase
      // Also handle relative-resolved paths
      const resolved = path.resolve(path.dirname(importer), source)
      if (resolved === path.resolve(__dirname, '../src/context/AppContext.jsx') ||
          resolved === path.resolve(__dirname, '../src/context/AppContext')) {
        return mockAppCtx
      }
      if (resolved === path.resolve(__dirname, '../src/supabase.js') ||
          resolved === path.resolve(__dirname, '../src/supabase')) {
        return mockSupabase
      }
      return null
    },
  }
}

/**
 * Storybook 10's MDX compiler embeds absolute file:// URLs in compiled output,
 * e.g. import ... from "file:///path/to/mdx-react-shim.js"
 * Vite's import-analysis chokes on these. Fix: rewrite them to bare paths
 * after the MDX transform runs (enforce: 'post' ensures we see compiled output).
 */
function mdxFileUrlFix(): Plugin {
  return {
    name: 'kaapu-mdx-fileurl-fix',
    enforce: 'post',
    transform(code, id) {
      if (!id.endsWith('.mdx')) return null
      // Replace: from "file:///absolute/path" → from "/absolute/path"
      const fixed = code.replace(/from\s+"file:\/\/([^"]+)"/g, 'from "$1"')
      return fixed !== code ? { code: fixed, map: null } : null
    },
  }
}

const config: StorybookConfig = {
  stories: [
    '../src/**/*.mdx',
    '../src/**/*.stories.@(js|jsx|mjs|ts|tsx)',
  ],
  addons: [
    '@chromatic-com/storybook',
    '@storybook/addon-vitest',
    '@storybook/addon-a11y',
    '@storybook/addon-docs',
    '@storybook/addon-mcp',
  ],
  framework: '@storybook/react-vite',
  staticDirs: ['../public'],
  async viteFinal(config) {
    config.plugins = [...(config.plugins ?? []), mockPlugin(), mdxFileUrlFix()]
    // In Storybook 10 @storybook/blocks is not a separate package; blocks live in addon-docs
    config.resolve = config.resolve ?? {}
    config.resolve.alias = {
      ...(config.resolve.alias as Record<string, string> ?? {}),
      '@storybook/blocks': '@storybook/addon-docs/blocks',
    }
    return config
  },
};
export default config;
